// スート表示の単一ソース（グリフ + 4色デッキの配色・契約12 項目2）。
// 3D カード面（cardTexture）・2D 手札カード・メルドチップ・捨て札チップなど、スートを表示する
// 全箇所がここを参照して配色/グリフの一貫性を保つ（DOM/three 非依存の純データ）。
//
// 4色デッキ: ♠=黒 / ♥=赤 / ♣=緑 / ♦=青。従来の2色（黒/赤）では ♠ と ♣ が形状のみの差で
// 卓上の遠距離・小サイズで見分けづらかった（ユーザー報告）ため、スートごとに色を分ける。
// ♣ の緑は卓のフェルト緑（felt.ts: #1f7a4d〜#0c3c26）と混同しないよう、より暗く高彩度の緑にして
// カード地（クリーム #f6f4ec）上で明度差を確保する。色覚多様性にも配慮し黒/赤/緑/青の明度を離す。
import type { Suit } from '../core';

export const SUIT_GLYPH: Record<Suit, string> = { S: '♠', H: '♥', C: '♣', D: '♦' };

export const SUIT_COLOR: Record<Suit, string> = {
  S: '#16161d', // スペード=黒（ほぼ黒・わずかに青み）
  H: '#c0212f', // ハート=赤
  C: '#0a7d38', // クラブ=緑（フェルト緑より暗く高彩度＝卓と混同しない）
  D: '#1461c2', // ダイヤ=青
};
